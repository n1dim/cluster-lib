#!/bin/bash

WORKER=./worker_app
CONTROL=./control_app
PASS=0
FAIL=0

run_test() {
    local name="$1"
    local expected_exit="$2"
    shift 2

    echo ""
    echo "=== $name ==="

    # запускаем команду, не позволяя bash прерваться при ненулевом коде
    "$@" > /dev/null 2>&1
    local actual=$?

    if [ "$actual" -eq "$expected_exit" ]; then
        echo "  PASS"
        PASS=$((PASS + 1))
    else
        echo "  FAIL (ожидался код $expected_exit, получен $actual)"
        FAIL=$((FAIL + 1))
    fi
}

# ─── Тест 1: два воркера ─────────────────────────────────────────────────
$WORKER 9101 2 30 &
$WORKER 9102 2 30 &
sleep 0.2
run_test "два воркера, вычисление пи" 0 \
    $CONTROL 2 30 127.0.0.1:9101 127.0.0.1:9102

# ─── Тест 2: один воркер ─────────────────────────────────────────────────
$WORKER 9103 4 30 &
sleep 0.2
run_test "один воркер, 4 ядра" 0 \
    $CONTROL 1 30 127.0.0.1:9103

# ─── Тест 3: четыре воркера ───────────────────────────────────────────────
$WORKER 9104 1 30 &
$WORKER 9105 1 30 &
$WORKER 9106 1 30 &
$WORKER 9107 1 30 &
sleep 0.2
run_test "четыре воркера по 1 ядру" 0 \
    $CONTROL 4 30 127.0.0.1:9104 127.0.0.1:9105 127.0.0.1:9106 127.0.0.1:9107

# ─── Тест 4: нет воркеров — ожидаем ошибку ───────────────────────────────
run_test "нет воркеров (ожидаем ошибку)" 1 \
    $CONTROL 1 5 127.0.0.1:9199

# ─── Тест 5: масштабирование ──────────────────────────────────────────────
echo ""
echo "=== масштабирование: 1×1 vs 2×2 ==="

$WORKER 9108 1 30 &
sleep 0.2
T1=$(TIMEFORMAT='%R'; { time $CONTROL 1 30 127.0.0.1:9108 > /dev/null 2>&1; } 2>&1)
echo "  1 воркер  × 1 ядро:  ${T1} с"

$WORKER 9109 2 30 &
$WORKER 9110 2 30 &
sleep 0.2
T2=$(TIMEFORMAT='%R'; { time $CONTROL 2 30 127.0.0.1:9109 127.0.0.1:9110 > /dev/null 2>&1; } 2>&1)
echo "  2 воркера × 2 ядра: ${T2} с"
PASS=$((PASS + 1))

# ─── Тест 6: воркер отключается во время вычисления ─────────────────────
# Симулируем воркер который принимает подключение, ждёт 0.3с, затем закрывает сокет.
# Контроллер должен обнаружить POLLHUP и завершиться с ошибкой.
echo ""
echo "=== воркер отключается во время вычисления (ожидаем ошибку контроллера) ==="
python3 -c "
import socket, time
s = socket.socket()
s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
s.bind(('', 9111))
s.listen(1)
conn, _ = s.accept()
time.sleep(0.3)
conn.close()
s.close()
" &
sleep 0.2
$CONTROL 1 5 127.0.0.1:9111 > /dev/null 2>&1
actual=$?
if [ "$actual" -ne 0 ]; then
    echo "  PASS (контроллер обнаружил отключение воркера)"
    PASS=$((PASS + 1))
else
    echo "  FAIL (контроллер не обнаружил отключение воркера)"
    FAIL=$((FAIL + 1))
fi

# ─── Тест 7: контроллер отключается во время вычисления ──────────────────
# Симулируем контроллер который подключается к воркеру, ждёт 0.3с, затем закрывает сокет.
# Воркер должен обнаружить EOF на read() и завершиться с ошибкой.
echo ""
echo "=== контроллер отключается во время вычисления (ожидаем ошибку воркера) ==="
$WORKER 9112 1 10 > /dev/null 2>&1 &
W=$!
sleep 0.2
python3 -c "
import socket, time
s = socket.socket()
s.connect(('127.0.0.1', 9112))
time.sleep(0.3)
s.close()
" > /dev/null 2>&1
wait $W
actual=$?
if [ "$actual" -ne 0 ]; then
    echo "  PASS (воркер обнаружил отключение контроллера)"
    PASS=$((PASS + 1))
else
    echo "  FAIL (воркер не обнаружил отключение контроллера)"
    FAIL=$((FAIL + 1))
fi

# ─── Тест 8: таймаут воркера (нет контроллера) ───────────────────────────
echo ""
echo "=== таймаут воркера (нет контроллера) ==="
$WORKER 9113 1 2 > /dev/null 2>&1 &
W=$!
wait $W
actual=$?
if [ "$actual" -ne 0 ]; then
    echo "  PASS (воркер завершился по таймауту)"
    PASS=$((PASS + 1))
else
    echo "  FAIL (воркер не завершился по таймауту)"
    FAIL=$((FAIL + 1))
fi

# ─── Итог ─────────────────────────────────────────────────────────────────
echo ""
echo "Результат: $PASS пройдено, $FAIL провалено"
[ "$FAIL" -eq 0 ]
